import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {expect} from '@playwright/test';
import {root} from '../../e2e/runtime-harness.mjs';
import {accessible,openPageAction} from './browser-support.mjs';
import {call,editable,grant,ok,restrictedPage,savedAfterCommit,withSecondPerson} from './two-people-support.mjs';

/** One populated page, retained references and independent readers across its lifetime. */
export async function pageIdentityJourney(state,width) {
  const {page,context,origin,api}=state;
  const directory=path.join(root,'.artifacts/ui-convergence/page-identity',String(width));
  await mkdir(directory,{recursive:true});
  const shot=name=>page.screenshot({path:path.join(directory,name+'.png'),fullPage:true});
  const mutate=(method,route,data)=>ok(context,origin,method,route,{operationKey:randomUUID(),...data});
  const workspace=await api('/api/workspace');
  const settings=async changes=>{
    const current=await api('/api/workspace');
    const {name,mark,description,guestAccess,publicLinkAccess,anonymousAccess,policies}=current;
    await mutate('PUT','/api/workspace',{expectedRevisionId:current.revisionId,name,mark,description,guestAccess,publicLinkAccess,anonymousAccess,policies,...changes});
  };
  // Exposure uses the native link profile; the original workspace policy is restored.
  await settings({publicLinkAccess:'allowed',anonymousAccess:'allowed',policies:{...workspace.policies,'page.public-access.v1':'link','page.version.v1':'labelled'}});
  const marker=`synthetic-slate-identity-${randomUUID()}`;
  const originalTitle='Retained response guide',renamedTitle='Renamed response guide';
  const originalBody=`${marker} Keep the original response instructions.`;
  const {pageId:id,spaceId,blockIds:[bodyId]}=await restrictedPage(state,originalTitle,[originalBody]);
  const create=(containerId,title,blocks=[])=>(mutate('POST','/api/pages',{containerId,title,blocks})).then(result=>result.value.pageId);
  const parent=await create(spaceId,'Identity destination parent');
  const destination=(await mutate('POST','/api/containers',{name:'Identity destination space',visibility:'private'})).value.id;
  const space=await api(`/api/containers/${destination}`);
  await mutate('POST','/api/sharing/container-settings',{id:destination,expectedRevisionId:space.revisionId,visibility:space.visibility,guestAccess:space.guestAccess,publicLinkAccess:'allowed',anonymousAccess:'allowed'});
  const initial=await api(`/api/pages/${id}`),revision=initial.workingRevisionId;
  const exact=await api(`/api/revisions/${id}/${revision}`);
  const citation=await api(`/api/pages/${id}/link-card?revision=${revision}`);
  assert.equal(citation.href,`/app/pages/${id}?revision=${revision}`);
  // Retain the permanent address generated by Share, rather than constructing the fixture's link.
  await page.goto(`${origin}/app/pages/${id}`,{waitUntil:'networkidle'});
  await openPageAction(page,'Share');
  await page.getByRole('button',{name:'Copy page link',exact:true}).click();
  await expect(page.getByRole('button',{name:'Link copied',exact:true})).toBeVisible();
  const permanent=await page.evaluate(()=>navigator.clipboard.readText());
  assert.equal(permanent,`${origin}/app/pages/${id}`);
  const referenceBlock=randomUUID();
  const reference=await create(spaceId,'Identity reference report',[{id:referenceBlock,blockType:'paragraph',treePosition:'a',content:{text:[
    {text:'Permanent guide',link:{href:permanent}},
    {text:' · '},{text:originalTitle,mention:{kind:'page',id,label:originalTitle}},
    {text:' · '},{text:'Original instructions',link:{href:citation.href}},
  ]}}]);
  // Save real search criteria through the search surface, then select them in a real query block.
  await page.goto(`${origin}/app/search?q=${encodeURIComponent(marker)}&kind=page`,{waitUntil:'networkidle'});
  await expect(page.locator('.search-results h2')).toHaveText([originalTitle]);
  await page.getByRole('button',{name:'Filter results',exact:true}).click();
  await page.getByRole('button',{name:'Save this search',exact:true}).click();
  const save=page.getByRole('dialog',{name:'Save search',exact:true});
  const searchName='Retained identity search';
  await save.getByLabel('Search name',{exact:true}).fill(searchName);
  await save.getByRole('button',{name:'Save search',exact:true}).click();
  await expect(save).toBeHidden();
  const saved=(await api('/api/search/saved')).items.find(item=>item.name===searchName);
  assert.ok(saved);
  assert.equal(saved.query.query,marker);
  await page.goto(`${origin}/app/pages/${reference}`,{waitUntil:'networkidle'});
  await page.getByRole('button',{name:/Add block/}).click();
  await page.getByPlaceholder('Type to search').fill('Content query');
  const added=page.waitForResponse(response=>new URL(response.url()).pathname===`/api/pages/${reference}/blocks`&&response.request().method()==='PUT');
  await page.getByRole('option',{name:'Content query',exact:true}).click();
  assert.equal((await added).status(),200);
  await expect(page.locator('.editor-save-status')).toHaveText('Saved');
  const query=view=>view.getByRole('region',{name:'Content query',exact:true});
  await query(page).getByRole('button',{name:'Edit the query',exact:true}).click();
  const edit=page.getByRole('dialog',{name:'Edit content query',exact:true});
  await edit.getByLabel('Saved search',{exact:true}).selectOption(saved.id);
  await shot('saved-content-query');
  await edit.getByRole('button',{name:'Save query',exact:true}).click();
  await expect(edit).toBeHidden();
  const definition=(await api(`/api/pages/${reference}`)).blocks.find(block=>block.blockType==='content-query').content.definition;
  const {limit:searchLimit,...embeddedCriteria}=saved.query;
  assert.deepEqual(definition.search,embeddedCriteria,'Embedding retains criteria; the block owns its result limit.');
  const pointers=doc=>{
    const spans=doc.blocks.find(block=>block.id===referenceBlock).content.text;
    return {links:spans.filter(span=>span.link).map(span=>span.link.href),mentions:spans.filter(span=>span.mention).map(span=>({kind:span.mention.kind,id:span.mention.id})),query:doc.blocks.find(block=>block.blockType==='content-query').content.definition};
  };
  const retained={links:[permanent,citation.href],mentions:[{kind:'page',id}],query:definition};
  const snapshots=[];
  try {
    await withSecondPerson(state,width,async people=>{
      const {bob}=people;
      await grant(context,origin,reference,bob.id,'view');
      const admission=await grant(context,origin,id,bob.id,'edit');
      let title=originalTitle,body=originalBody;
      const searchRoute=`/api/search?q=${encodeURIComponent(marker)}&kind=page`;
      const reconcile=async(label,{archived=false,trashed=false,revoked=false}={})=>{
        const readable=!trashed&&!revoked,listed=readable&&!archived;
        const current=trashed?(await api('/api/archive')).items.find(item=>item.id===id):(await api(`/api/pages/${id}`)).page;
        assert.ok(current,`${label}: original identifier remains stored.`);
        assert.equal(current.id,id);
        assert.equal(current.title,title);
        assert.deepEqual(pointers(await api(`/api/pages/${reference}`)),retained,`${label}: every retained reference still targets its original identity.`);
        assert.deepEqual((await api('/api/search/saved')).items.find(item=>item.id===saved.id),saved,`${label}: saved criteria have not been replaced.`);
        // The reader's projected links and query retain their identifiers even while access is denied.
        const report=await ok(bob.context,origin,'GET',`/api/pages/${reference}`);
        assert.deepEqual(pointers(report),retained);
        const mention=report.mentions[id];
        assert.equal(mention.available,readable);
        assert.equal(mention.state,revoked?'restricted':trashed?'trashed':archived?'archived':'live');
        if(readable)assert.equal(mention.label,title);
        if(revoked)assert.equal(mention.label,'Restricted page');
        const found=await ok(bob.context,origin,'GET',searchRoute);
        assert.deepEqual(found.items.map(item=>item.id),listed?[id]:[],`${label}: search uses current lifecycle and grants.`);
        if(listed)assert.equal(found.items[0].href,`/app/pages/${id}`);
        const results=await ok(bob.context,origin,'POST',`/api/pages/${reference}/query`,definition);
        assert.deepEqual(results.items.map(item=>item.id),listed?[id]:[],`${label}: query reappearance uses the original identifier.`);
        const card=await call(bob.context,origin,'GET',`/api/pages/${id}/link-card?revision=${revision}`);
        assert.equal(card.status,readable?200:404);
        if(readable){
          assert.equal(card.body.href,citation.href);
          const cited=await ok(bob.context,origin,'GET',`/api/revisions/${id}/${revision}`);
          assert.deepEqual(cited.blocks,exact.blocks,`${label}: exact cited content has not changed.`);
          assert.deepEqual(cited.properties,exact.properties);
        }
        // Independent reader navigation and reload exercise the retained address, not the owner's editor state.
        await bob.page.goto(permanent,{waitUntil:'networkidle'});
        await bob.page.reload({waitUntil:'networkidle'});
        if(readable){
          await expect(bob.page.getByRole('textbox',{name:'Page title',exact:true})).toHaveValue(title);
          await expect(bob.page.locator(`[data-block-id="${bodyId}"]`)).toContainText(body);
          assert.equal((await ok(bob.context,origin,'GET',`/api/pages/${id}`)).page.id,id);
          await bob.page.goto(new URL(citation.href,origin).href,{waitUntil:'networkidle'});
          await expect(bob.page.locator('.revision-preview')).toContainText(originalBody);
          await expect(bob.page.locator('.revision-preview')).toContainText(originalTitle);
          await expect(bob.page.locator('.revision-preview')).not.toContainText('Follow the updated escalation step.');
        } else {
          await expect(bob.page.getByRole('heading',{name:'Access needed',exact:true})).toBeVisible();
          await expect(bob.page.locator('.page-document')).not.toContainText(marker);
          await expect(bob.page.locator('.page-document')).not.toContainText(title);
          assert.equal((await call(bob.context,origin,'GET',`/api/pages/${id}`)).status,404);
        }
        await bob.page.goto(`${origin}/app/pages/${reference}`,{waitUntil:'networkidle'});
        await bob.page.reload({waitUntil:'networkidle'});
        const editor=bob.page.locator('[data-page-editor]');
        await expect(editor.getByRole('link',{name:'Permanent guide',exact:true})).toHaveAttribute('href',permanent);
        await expect(editor.getByRole('link',{name:'Original instructions',exact:true})).toHaveAttribute('href',citation.href);
        const visibleMention=editor.locator('[data-mention-kind=page]');
        if(readable)await expect(visibleMention.getByRole('link',{name:title,exact:true})).toHaveAttribute('href',`/app/pages/${id}`);
        else await expect(visibleMention.getByRole('link')).toHaveCount(0);
        await expect(query(bob.page).locator('tbody tr button')).toHaveText(listed?[title]:[]);
        await expect(query(bob.page).locator('footer')).toContainText(listed?'· 1 item':'· 0 items');
        // The saved search is reopened from native controls after every commit and reload.
        await page.goto(`${origin}/app/search`,{waitUntil:'networkidle'});
        await page.getByRole('button',{name:'Filter results',exact:true}).click();
        await page.getByRole('button',{name:searchName,exact:true}).click();
        await expect(page.getByRole('searchbox',{name:'Search your workspace',exact:true})).toHaveValue(marker);
        await page.reload({waitUntil:'networkidle'});
        await expect(page.locator('.search-results h2')).toHaveText(!trashed&&!archived?[title]:[]);
        if(trashed||archived)await expect(page.locator('.search-empty')).toContainText(`No matches for “${marker}”.`);
        snapshots.push({label,id,title,revisionId:trashed?current.revisionId:(await api(`/api/pages/${id}`)).page.revisionId,retained,reader:{mention,search:found.items.map(item=>item.id),query:results.items.map(item=>item.id)}});
        await writeFile(path.join(directory,'snapshots.json'),JSON.stringify({id,permanent,citation:citation.href,revision,savedSearch:saved,reference,snapshots},null,2));
        console.log(`PROBE PAGE-003 ${label}: retained addresses, mention, exact revision, saved query and search -> ${id}; readable=${readable}; listed=${listed}`);
      };
      await reconcile('created');
      await page.goto(permanent,{waitUntil:'networkidle'});
      await savedAfterCommit(page,null,()=>page.getByRole('textbox',{name:'Page title',exact:true}).fill(renamedTitle));
      title=renamedTitle;
      await reconcile('renamed');
      await page.goto(permanent,{waitUntil:'networkidle'});
      const edited=await savedAfterCommit(page,bodyId,()=>editable(page,bodyId).fill(`${originalBody} Follow the updated escalation step.`));
      body=`${originalBody} Follow the updated escalation step.`;
      await reconcile('edited');
      const move=async(name,containerId,parentPageId)=>{
        await page.goto(permanent,{waitUntil:'networkidle'});
        await page.getByRole('button',{name:'More',exact:true}).click();
        await page.getByRole('menuitem',{name:'Move page',exact:true}).click();
        const picker=page.getByRole('dialog',{name:`Move “${title}”`,exact:true});
        await picker.getByPlaceholder('Search for a destination').fill(name);
        await picker.getByRole('option',{name:parentPageId?`${name} Handbook`:name,exact:true}).click();
        await picker.getByRole('button',{name:'Move page',exact:true}).click();
        const review=page.getByRole('dialog',{name:'Review changed access',exact:true});
        const committed=page.waitForResponse(response=>new URL(response.url()).pathname===`/api/pages/${id}/move`&&response.request().method()==='POST');
        await shot(parentPageId?'move-within':'move-between');
        await review.getByRole('button',{name:'Move page',exact:true}).click();
        assert.equal((await committed).status(),200);
        await expect(review).toBeHidden();
        const moved=await api(`/api/pages/${id}`);
        assert.equal(moved.page.id,id);assert.equal(moved.page.containerId,containerId);assert.equal(moved.parentPageId,parentPageId);
      };
      await move('Identity destination parent',spaceId,parent);
      await reconcile('moved within space');
      await move('Identity destination space',destination,null);
      await reconcile('moved between spaces');
      const remove=async(action)=>{
        await page.goto(permanent,{waitUntil:'networkidle'});
        await page.getByRole('button',{name:'More',exact:true}).click();
        await page.getByRole('menuitem',{name:action==='archive'?'Archive page':'Move to trash',exact:true}).click();
        const dialog=page.getByRole('dialog',{name:action==='archive'?'Archive this page?':'Move this page to trash?',exact:true});
        await dialog.getByLabel('Reason',{exact:true}).fill('Retain the same guide and its references.');
        const committed=page.waitForResponse(response=>new URL(response.url()).pathname===`/api/archive/${id}`&&response.request().method()==='POST');
        await shot(action);
        await dialog.getByRole('button',{name:'Confirm',exact:true}).click();
        assert.equal((await committed).status(),200);
        await expect(dialog).toBeHidden();
      };
      const restore=async(trash)=>{
        await page.goto(`${origin}/app/archive`,{waitUntil:'networkidle'});
        if(trash)await page.getByRole('button',{name:'Trash',exact:true}).click();
        const row=page.locator('.archive-list li').filter({hasText:title});
        const committed=page.waitForResponse(response=>new URL(response.url()).pathname===`/api/archive/${id}`&&response.request().method()==='POST');
        await shot(trash?'restore-trash':'restore-archive');
        await row.getByRole('button',{name:'Restore',exact:true}).click();
        assert.equal((await committed).status(),200);
        await expect(row).toHaveCount(0);
      };
      await remove('archive');await reconcile('archived',{archived:true});
      assert.deepEqual((await ok(bob.context,origin,'GET',searchRoute+'&includeArchived=true')).items.map(item=>item.id),[id]);
      await restore(false);await reconcile('restored from archive');
      await remove('trash');await reconcile('trashed',{trashed:true});
      await restore(true);await reconcile('restored from trash');
      // Workspace publication and web exposure are distinct native actions on the same page.
      await page.goto(permanent,{waitUntil:'networkidle'});
      await page.getByRole('button',{name:'More',exact:true}).click();
      await page.getByRole('menuitem',{name:'Publish workspace revision',exact:true}).click();
      const publication=page.getByRole('dialog',{name:'Publish this revision',exact:true});
      await publication.getByRole('button',{name:'Review publication',exact:true}).click();
      const published=page.waitForResponse(response=>new URL(response.url()).pathname===`/api/pages/${id}/publish`&&response.request().method()==='POST');
      await shot('reviewed-publication');
      await publication.getByRole('button',{name:'Publish workspace revision',exact:true}).click();
      assert.equal((await published).status(),200);
      await expect(publication).toBeHidden();
      await reconcile('workspace published');
      await page.goto(permanent,{waitUntil:'networkidle'});
      await openPageAction(page,'Public access');
      await page.getByRole('switch',{name:'Public link',exact:true}).click();
      await expect(page.getByRole('switch',{name:'Public link',exact:true})).toBeChecked();
      await shot('web-published');
      const exposure=(await api(`/api/publishing/${id}`)).exposure;
      const publicAddress=`${origin}/p/${exposure.slug}`;
      const anonymous=await fetch(publicAddress);assert.equal(anonymous.status,200);assert.match(await anonymous.text(),/Follow the updated escalation step/);
      await reconcile('web published');
      await page.goto(permanent,{waitUntil:'networkidle'});
      await openPageAction(page,'Public access');
      await page.getByRole('switch',{name:'Public link',exact:true}).click();
      await expect(page.getByRole('switch',{name:'Public link',exact:true})).not.toBeChecked();
      await shot('web-unpublished');
      const stopped=await fetch(publicAddress);
      assert.equal(stopped.status,404);
      assert.equal((await stopped.text()).includes(marker),false,'Unpublishing exposes no retained body.');
      assert.equal((await api(`/api/publishing/${id}`)).exposure.slug,exposure.slug);
      await reconcile('unpublished');
      // Current grants dominate retained references; a captured write never resurrects access.
      await grant(context,origin,id,bob.id,'edit',{id:admission.value.id,revoke:true});
      const before=await api(`/api/pages/${id}`);
      const replay=await call(bob.context,origin,'PATCH',`/api/pages/${id}/blocks/${bodyId}`,{operationKey:edited.receipt.operationKey,expectedRevisionId:initial.blocks[0].revisionId,content:{text:[{text:body}]}});
      assert.equal(replay.status,404);
      assert.deepEqual(await api(`/api/pages/${id}`),before);
      await reconcile('grant revoked',{revoked:true});
      await grant(context,origin,id,bob.id,'edit');
      await reconcile('grant renewed');
      // Follow each retained reference through its native control at the final state.
      const permanentPopup=bob.page.waitForEvent('popup');
      await bob.page.getByRole('link',{name:'Permanent guide',exact:true}).click();
      const opened=await permanentPopup;
      await expect(opened.getByRole('textbox',{name:'Page title',exact:true})).toHaveValue(title);
      await opened.close();
      const citationPopup=bob.page.waitForEvent('popup');
      await bob.page.getByRole('link',{name:'Original instructions',exact:true}).click();
      const cited=await citationPopup;await expect(cited.locator('.revision-preview')).toContainText(originalBody);await cited.close();
      await bob.page.locator('[data-page-editor] [data-mention-kind=page] a').click();
      await expect(bob.page).toHaveURL(permanent);
      await bob.page.goto(`${origin}/app/pages/${reference}`,{waitUntil:'networkidle'});
      await query(bob.page).getByRole('button',{name:title,exact:true}).click();
      await expect(bob.page).toHaveURL(permanent);
      await page.locator('.search-results a').filter({has:page.getByRole('heading',{name:title,exact:true})}).click();
      await expect.poll(()=>new URL(page.url()).pathname).toBe(`/app/pages/${id}`);
      await expect(page.getByRole('textbox',{name:'Page title',exact:true})).toHaveValue(title);
      await accessible(page,'page identity retained guide');
      await bob.page.goto(`${origin}/app/pages/${reference}`,{waitUntil:'networkidle'});
      await accessible(bob.page,'page identity retained references and query');
      await writeFile(path.join(directory,'snapshots.json'),JSON.stringify({id,permanent,citation:citation.href,revision,savedSearch:saved,reference,snapshots},null,2));
    });
  } finally {
    await settings({publicLinkAccess:workspace.publicLinkAccess,anonymousAccess:workspace.anonymousAccess,policies:workspace.policies});
  }
}
