import assert from 'node:assert/strict';
import { expect } from '@playwright/test';
import { accessible, openNavigation } from './browser-support.mjs';
import { compactPage, savedAfterSaving, watchSaveStates } from './browser-evidence.mjs';
import { randomBytes } from 'node:crypto';
import { secondaryCreateDestinations } from './navigation-journey.mjs';
import { firstWordsJourney } from './first-words-journey.mjs';
import { savedAfterCommit } from './two-people-support.mjs';

export async function writeJourney(state, width) {
  const { page, origin, api } = state;
  state.searchTerm = `escalation${randomBytes(6).toString('hex')}`;
  state.journeyTitle = `Escalation guide ${state.searchTerm}`;
  await page.goto(origin + '/app', { waitUntil: 'networkidle' });
  await openNavigation(page);
  const navigation = page.getByRole('navigation', { name: 'Workspace navigation' });
  await expect(navigation.getByRole('link', { name: 'Spaces', exact: true })).toBeVisible();
  const icons = await navigation.locator('a svg').evaluateAll(elements => elements.map(element => element.innerHTML));
  assert.ok(icons.length >= 6);
  assert.equal(new Set(icons).size, icons.length, 'Primary navigation icons are distinct.');
  await expect(page.getByRole('button', { name: 'Create', exact: true })).toHaveCount(1);
  await expect(page.getByRole('button', { name: 'Create a page', exact: true })).toHaveCount(0);
  await expect(page.locator('body')).not.toContainText(/\bContainers?\b/);
  await accessible(page, 'home');
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  const menu = page.getByRole('menu', { name: 'Create content' });
  await expect(menu).toBeVisible();
  for (const name of ['Page', 'Database', 'Space', 'Page from template']) await expect(menu.getByRole('menuitem', { name, exact: true })).toBeVisible();
  await accessible(page, 'create menu');
  await page.keyboard.press('ArrowDown');
  await expect(menu.getByRole('menuitem', { name: 'Database', exact: true })).toBeFocused();
  await page.keyboard.press('End');
  await expect(menu.getByRole('menuitem', { name: 'Page from template', exact: true })).toBeFocused();
  for (const option of await menu.locator('button,a').all()) {
    const box = await option.boundingBox();
    assert.ok(box && box.height >= 32, 'Create options are separate touch targets.');
  }
  await page.keyboard.press('Escape');
  await expect(menu).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Create', exact: true })).toBeFocused();
  await secondaryCreateDestinations(state);
  const handbook = (await api('/api/containers')).items.find(space => space.name === 'Handbook');
  const pagesBefore = (await api('/api/pages')).items.length;
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  const createPage = page.getByRole('menu', { name: 'Create content' }).getByRole('menuitem', { name: 'Page', exact: true });
  // The menu names the inferred destination before anything is created.
  await expect(createPage).toHaveAccessibleDescription(/Handbook/);
  await createPage.click();
  await page.waitForURL(url => url.pathname.startsWith('/app/pages/'));
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const title = page.getByLabel('Page title', { exact: true });
  await expect(title).toBeFocused();
  const pageId = new URL(page.url()).pathname.split('/').at(-1);
  const createdPage = await api(`/api/pages/${pageId}`);
  assert.equal(createdPage.page.containerId, handbook.id);
  assert.ok(createdPage.page.title.length > 0, 'A new page starts with a default title.');
  assert.equal(await title.evaluate(element => [element.selectionStart, element.selectionEnd].join()), `0,${createdPage.page.title.length}`, 'The default title arrives selected.');
  assert.equal((await api('/api/pages')).items.length, pagesBefore + 1, 'One Create makes exactly one page.');
  await savedAfterCommit(page, undefined, async () => {
    await page.keyboard.type(state.journeyTitle);
    await expect(title).toHaveValue(state.journeyTitle);
    await title.press('Tab');
  }, { whileSaving: () => page.screenshot({ path: `.artifacts/ui-convergence/title-saving-${width}.png`, fullPage: true }) });
  await expect(page.getByRole('status').filter({ hasText: /^Saved$/ })).toBeVisible();
  assert.equal((await api(`/api/pages/${pageId}`)).page.title, state.journeyTitle);
  if (width !== 390) await expect(page.locator('aside.sidebar nav.page-links').getByRole('link', { name: state.journeyTitle })).toBeVisible();
  await accessible(page, 'create page');
  await expect(page.getByRole('textbox', { name: 'Page body', exact: true })).toBeVisible();
  const body = page.getByRole('textbox', { name: 'Page body', exact: true });
  const emptyBox = await body.boundingBox();
  const add = page.getByRole('button', { name: /Add block/, exact: false });
  const addBox = await add.boundingBox();
  assert.ok(emptyBox && addBox && addBox.y >= emptyBox.y + emptyBox.height, 'Add block follows the writable empty body.');
  await expect(page.locator('.page-status-chip')).toHaveCount(0);
  await expect(page.locator('.page-document')).not.toContainText(/No status|Not verified|Status & verification/);
  await expect(page.locator('.page-byline')).toContainText('Owner: Alex Owner');
  await expect(page.locator('.page-byline time')).toContainText('Updated');
  await compactPage(page);
  if (width === 390) {
    assert.ok(emptyBox.y < 844 * .45, 'Mobile content begins above 45% of the viewport.');
    // The page toolbar itself is outside content-frame in the app shell.
    const toolbarPositions = await page.locator('.topbar .tools button').evaluateAll(elements => elements.filter(element => element.getBoundingClientRect().width > 0 && element.getBoundingClientRect().height > 0).map(element => Math.round(element.getBoundingClientRect().y)));
    assert.ok(toolbarPositions.length >= 3);
    assert.equal(new Set(toolbarPositions).size, 1, 'Mobile page actions occupy one row.');
  }
  await body.click();
  await expect(body).toBeFocused();
  await page.keyboard.press('Tab');
  await page.keyboard.press('Shift+Tab');
  await expect(body).toBeFocused();
  await watchSaveStates(page);
  await body.fill('The on-call lead owns escalation decisions.');
  await expect(page.getByRole('textbox', { name: 'Paragraph', exact: true })).toBeVisible();
  await savedAfterSaving(page);
  const committed = (await api(`/api/pages/${pageId}`)).blocks;
  assert.ok(JSON.stringify(committed).includes('The on-call lead owns escalation decisions.'));
  await page.reload({ waitUntil: 'networkidle' });
  const paragraph = page.getByRole('textbox', { name: 'Paragraph', exact: true }).first();
  await expect(paragraph).toContainText('The on-call lead owns escalation decisions.');
  await accessible(page, 'saved page');
  // Genuine transport loss: the server retains its last committed value while the editor keeps the new draft.
  await page.context().setOffline(true);
  await paragraph.fill('The on-call lead owns escalation decisions. Keep this unsent detail.');
  await expect(page.getByRole('status').filter({ hasText: /Offline|Not saved/ }).first()).toBeVisible();
  await expect(page.locator('[data-block-id]').first().getByRole('status').filter({ hasText: /^Saved/ })).toHaveCount(0);
  await expect(paragraph).toContainText('Keep this unsent detail.');
  await accessible(page, 'offline save retains text');
  await page.context().setOffline(false);
  const beforeRetry = await api(`/api/pages/${pageId}`);
  assert.deepEqual(beforeRetry.blocks, committed, 'Real backend retains only prior committed text before retry.');
  await page.waitForTimeout(900);
  assert.deepEqual((await api(`/api/pages/${pageId}`)).blocks, committed, 'Connection restoration alone does not commit the unsent draft.');
  await accessible(page, 'failed save retains text');
  await watchSaveStates(page);
  const firstBlockId = await page.locator('[data-block-id]').first().getAttribute('data-block-id');
  await savedAfterCommit(page, firstBlockId, () => page.getByRole('button', { name: 'Try saving again', exact: true }).click(), {
    whileSaving: () => page.screenshot({ path: `.artifacts/ui-convergence/body-saving-${width}.png`, fullPage: true }),
  });
  await savedAfterSaving(page);
  assert.ok(JSON.stringify((await api(`/api/pages/${pageId}`)).blocks).includes('Keep this unsent detail.'));
  await page.reload({ waitUntil: 'networkidle' });
  await expect(title).toHaveValue(state.journeyTitle);
  await expect(page.getByRole('textbox', { name: 'Paragraph', exact: true }).first()).toContainText('Keep this unsent detail.');
  const firstBlockBox = await page.locator('[data-block-id]').first().boundingBox();
  const afterContent = await add.boundingBox();
  assert.ok(firstBlockBox && afterContent && afterContent.y >= firstBlockBox.y + firstBlockBox.height, 'Add block follows existing content.');
  await add.click();
  await page.getByRole('option', { name: 'Text', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Paragraph', exact: true })).toHaveCount(2);
  await watchSaveStates(page);
  await page.getByRole('textbox', { name: 'Paragraph', exact: true }).nth(1).fill(`Second block: record the next action. ${state.searchTerm}`);
  await expect(page.getByRole('status').filter({ hasText: /^Saved/ }).last()).toBeVisible();
  await expect.poll(async () => JSON.stringify((await api(`/api/pages/${pageId}`)).blocks)).toContain('Second block: record the next action.');
  await savedAfterSaving(page);
  await page.reload({ waitUntil: 'networkidle' });
  const paragraphs = page.getByRole('textbox', { name: 'Paragraph', exact: true });
  await expect(paragraphs).toHaveCount(2);
  await expect(paragraphs.nth(0)).toContainText('Keep this unsent detail.');
  await expect(paragraphs.nth(1)).toContainText('Second block: record the next action.');
  await accessible(page, 'two blocks saved in order');
  await firstWordsJourney(state);
  await page.goto(`${origin}/app/pages/${pageId}`, { waitUntil: 'networkidle' });
  return pageId;
}
